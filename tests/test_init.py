async def test_refresh_service(hass: HomeAssistant, mock_config_entry: MockConfigEntry):
    """Calling ``mashov.refresh_now`` for an entry triggers a coordinator fetch."""
    mock_config_entry.add_to_hass(hass)

    with patch("custom_components.mashov.MashovClient") as mock_client:
        client = mock_client.return_value
        client.async_init = AsyncMock(return_value=None)
        client.async_close = AsyncMock(return_value=None)
        client.async_open_session = AsyncMock(return_value=None)
        client.async_close_session = AsyncMock(return_value=None)
        client.async_authenticate = AsyncMock(return_value=True)
        client.async_fetch_all = AsyncMock(
            return_value={
                "students": [
                    {
                        "id": "student-123",
                        "name": "Test Student",
                        "slug": "student-123",
                        "year": "2024",
                        "school_id": "123456",
                    }
                ],
                "by_slug": {
                    "student-123": {
                        "homework": [],
                        "behavior": [],
                        "weekly_plan": [],
                        "timetable": [],
                        "lessons_history": [],
                    }
                },
                "holidays": [],
            }
        )
        client.async_get_students = AsyncMock(return_value=[TEST_STUDENT])

        assert await hass.config_entries.async_setup(mock_config_entry.entry_id)
        await hass.async_block_till_done()

        # Test refresh_now service
        await hass.services.async_call(
            DOMAIN,
            "refresh_now",
            {"entry_id": mock_config_entry.entry_id},
            blocking=True,
        )
        await hass.async_block_till_done()

        # Verify coordinator refresh was called (async_fetch_all is called during refresh)
        assert client.async_fetch_all.call_count >= 1
